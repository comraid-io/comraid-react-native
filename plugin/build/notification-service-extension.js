'use strict';

const fs = require('fs');
const path = require('path');

const NSE_TARGET_NAME = 'ComRaidNotificationService';
const NSE_BUNDLE_SUFFIX = 'ComRaidNotificationService';
const NSE_SWIFT_FILE = 'NotificationService.swift';
const NSE_PLIST_FILE = `${NSE_TARGET_NAME}-Info.plist`;
const NSE_ENTITLEMENTS_FILE = `${NSE_TARGET_NAME}.entitlements`;
const DEFAULT_DEPLOYMENT_TARGET = '15.1';
const PODFILE_TAG = 'comraid-notification-service';

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function escapeSwiftString(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/**
 * Notification Service Extension Swift source.
 * Calls `RemoteNotificationDisplay.enrich` (delivered ACK + image/buttons). When
 * `storageSuiteName` is set, passes it so the extension reads App Group config.
 * @param {{ storageSuiteName?: string }} [options]
 */
function notificationServiceSwiftSource({ storageSuiteName } = {}) {
  const suite = typeof storageSuiteName === 'string' ? storageSuiteName.trim() : '';
  const enrichCall = suite
    ? `RemoteNotificationDisplay.enrich(request, storageSuiteName: "${escapeSwiftString(suite)}")`
    : 'RemoteNotificationDisplay.enrich(request)';
  return `import ComRaid
import UserNotifications

/// Generated by @comraid/react-native. Attaches \`cr_image_url\`, registers action buttons,
/// and sends the delivered ACK via the shared App Group (\`storageSuiteName\`).
final class NotificationService: UNNotificationServiceExtension {
  private var contentHandler: ((UNNotificationContent) -> Void)?
  private var originalContent: UNNotificationContent?

  override func didReceive(
    _ request: UNNotificationRequest,
    withContentHandler contentHandler: @escaping (UNNotificationContent) -> Void
  ) {
    self.contentHandler = contentHandler
    originalContent = request.content
    Task {
      let content = await ${enrichCall}
      DispatchQueue.main.async { self.deliver(content) }
    }
  }

  override func serviceExtensionTimeWillExpire() {
    // Out of time: show the push without the image rather than dropping it.
    DispatchQueue.main.async {
      if let original = self.originalContent { self.deliver(original) }
    }
  }

  private func deliver(_ content: UNNotificationContent) {
    guard let handler = contentHandler else { return }
    contentHandler = nil
    handler(content)
  }
}
`;
}

/** Default generated source (no suite baked in). Prefer `notificationServiceSwiftSource`. */
const NSE_SWIFT_SOURCE = notificationServiceSwiftSource();

/**
 * Info.plist for the extension. Versions must match the host app or App Store validation fails.
 * @param {{ version: string, buildNumber: string }} versions
 */
function notificationServicePlist({ version, buildNumber }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key>
  <string>$(DEVELOPMENT_LANGUAGE)</string>
  <key>CFBundleDisplayName</key>
  <string>${NSE_TARGET_NAME}</string>
  <key>CFBundleExecutable</key>
  <string>$(EXECUTABLE_NAME)</string>
  <key>CFBundleIdentifier</key>
  <string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>CFBundleName</key>
  <string>$(PRODUCT_NAME)</string>
  <key>CFBundlePackageType</key>
  <string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
  <key>CFBundleShortVersionString</key>
  <string>${escapeXml(version)}</string>
  <key>CFBundleVersion</key>
  <string>${escapeXml(buildNumber)}</string>
  <key>NSExtension</key>
  <dict>
    <key>NSExtensionPointIdentifier</key>
    <string>com.apple.usernotifications.service</string>
    <key>NSExtensionPrincipalClass</key>
    <string>$(PRODUCT_MODULE_NAME).NotificationService</string>
  </dict>
</dict>
</plist>
`;
}

/**
 * Entitlements plist for the extension (App Group shared with the host).
 * @param {string} storageSuiteName App Group / UserDefaults suite id
 */
function notificationServiceEntitlements(storageSuiteName) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>com.apple.security.application-groups</key>
  <array>
    <string>${escapeXml(storageSuiteName)}</string>
  </array>
</dict>
</plist>
`;
}

const COMRAID_POD_PATH_TAG = 'comraid-pod-path';

/**
 * Pins `ComRaid` to a local checkout so CocoaPods does not need trunk (idempotent).
 * @param {string} podfile
 * @param {string} comraidPath Path to the comraid-ios repo (relative to ios/)
 */
function applyComraidPodPathOverride(podfile, comraidPath) {
  const trimmed = typeof comraidPath === 'string' ? comraidPath.trim() : '';
  if (!trimmed) return podfile;
  if (podfile.includes(`# @generated begin ${COMRAID_POD_PATH_TAG}`)) {
    return podfile;
  }
  const escaped = trimmed.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const block = `# @generated begin ${COMRAID_POD_PATH_TAG}
pod 'ComRaid', :path => '${escaped}'
# @generated end ${COMRAID_POD_PATH_TAG}
`;
  const platform = podfile.match(/^platform[^\n]*\n+/m);
  if (platform) {
    return podfile.replace(platform[0], `${platform[0]}${block}\n`);
  }
  return `${block}\n${podfile}`;
}

/**
 * Adds a Podfile target so the extension links the ComRaid pod (idempotent).
 * @param {string} podfile
 * @param {{ comraidPath?: string }} [options]
 */
function addNotificationServicePodTarget(podfile, options = {}) {
  if (podfile.includes(`target '${NSE_TARGET_NAME}'`)) {
    return podfile;
  }
  const trimmed =
    typeof options.comraidPath === 'string' ? options.comraidPath.trim() : '';
  const podLine = trimmed
    ? `  pod 'ComRaid', :path => '${trimmed.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
    : `  pod 'ComRaid'`;
  // Top level, beside the app target; version comes from ReactNativeComraid unless :path is set.
  return `${podfile.trimEnd()}

# @generated begin ${PODFILE_TAG}
target '${NSE_TARGET_NAME}' do
${podLine}
end
# @generated end ${PODFILE_TAG}
`;
}

/**
 * Writes the extension's Swift source, Info.plist, and optional entitlements under `ios/<target>/`.
 * @param {string} iosRoot
 * @param {{ version: string, buildNumber: string, storageSuiteName?: string }} options
 */
function writeNotificationServiceFiles(iosRoot, options) {
  const { storageSuiteName, ...versions } = options;
  const dir = path.join(iosRoot, NSE_TARGET_NAME);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, NSE_SWIFT_FILE),
    notificationServiceSwiftSource({ storageSuiteName }),
  );
  fs.writeFileSync(path.join(dir, NSE_PLIST_FILE), notificationServicePlist(versions));
  const suite = typeof storageSuiteName === 'string' ? storageSuiteName.trim() : '';
  if (suite) {
    fs.writeFileSync(path.join(dir, NSE_ENTITLEMENTS_FILE), notificationServiceEntitlements(suite));
  }
}

function unquote(value) {
  return typeof value === 'string' ? value.replace(/^"(.*)"$/, '$1') : value;
}

/** First build setting value for the host app target, across its configurations. */
function hostBuildSetting(project, key) {
  const nativeTarget = project.getFirstTarget().firstTarget;
  const list = project.pbxXCConfigurationList()[nativeTarget.buildConfigurationList];
  const configurations = project.pbxXCBuildConfigurationSection();
  for (const ref of list?.buildConfigurations ?? []) {
    const value = configurations[ref.value]?.buildSettings?.[key];
    if (value != null) return unquote(value);
  }
  return undefined;
}

/**
 * Adds the Notification Service Extension target to the Xcode project and embeds it in the app
 * (idempotent: an existing target with the same name is left untouched).
 * @param {import('xcode').XcodeProject} project
 * @param {{ bundleIdentifier: string, developmentTeam?: string, version: string, buildNumber: string, storageSuiteName?: string }} options
 */
function addNotificationServiceTarget(project, options) {
  if (project.pbxTargetByName(NSE_TARGET_NAME)) {
    return project;
  }
  const objects = project.hash.project.objects;
  // addTarget makes the app depend on the extension; node-xcode assumes these sections exist.
  objects.PBXTargetDependency = objects.PBXTargetDependency || {};
  objects.PBXContainerItemProxy = objects.PBXContainerItemProxy || {};

  const suite = typeof options.storageSuiteName === 'string' ? options.storageSuiteName.trim() : '';
  const groupChildren = suite
    ? [NSE_SWIFT_FILE, NSE_PLIST_FILE, NSE_ENTITLEMENTS_FILE]
    : [NSE_SWIFT_FILE, NSE_PLIST_FILE];
  const group = project.addPbxGroup(groupChildren, NSE_TARGET_NAME, NSE_TARGET_NAME);
  const mainGroupId = project.getFirstProject().firstProject.mainGroup;
  project.addToPbxGroup(group.uuid, mainGroupId);

  const target = project.addTarget(
    NSE_TARGET_NAME,
    'app_extension',
    NSE_TARGET_NAME,
    `${options.bundleIdentifier}.${NSE_BUNDLE_SUFFIX}`,
  );
  project.addBuildPhase([NSE_SWIFT_FILE], 'PBXSourcesBuildPhase', 'Sources', target.uuid);
  project.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);
  project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

  const developmentTeam = options.developmentTeam ?? hostBuildSetting(project, 'DEVELOPMENT_TEAM');
  const deploymentTarget =
    hostBuildSetting(project, 'IPHONEOS_DEPLOYMENT_TARGET') ?? DEFAULT_DEPLOYMENT_TARGET;
  const deviceFamily = hostBuildSetting(project, 'TARGETED_DEVICE_FAMILY') ?? '1,2';
  const configurations = project.pbxXCBuildConfigurationSection();
  for (const key of Object.keys(configurations)) {
    const settings = configurations[key].buildSettings;
    if (!settings || unquote(settings.PRODUCT_NAME) !== NSE_TARGET_NAME) continue;
    Object.assign(settings, {
      APPLICATION_EXTENSION_API_ONLY: 'YES',
      CLANG_ENABLE_MODULES: 'YES',
      CODE_SIGN_STYLE: 'Automatic',
      CURRENT_PROJECT_VERSION: `"${options.buildNumber}"`,
      GENERATE_INFOPLIST_FILE: 'NO',
      IPHONEOS_DEPLOYMENT_TARGET: deploymentTarget,
      MARKETING_VERSION: `"${options.version}"`,
      SDKROOT: 'iphoneos',
      SWIFT_VERSION: '5.0',
      TARGETED_DEVICE_FAMILY: `"${deviceFamily}"`,
    });
    if (suite) {
      settings.CODE_SIGN_ENTITLEMENTS = `${NSE_TARGET_NAME}/${NSE_ENTITLEMENTS_FILE}`;
    }
    if (developmentTeam) {
      settings.DEVELOPMENT_TEAM = developmentTeam;
    }
  }
  return project;
}

/**
 * Registers the extension with EAS Build so it provisions a profile for the extension bundle id.
 * @param {Record<string, any>} config Expo config
 * @param {string} bundleIdentifier Host app bundle id
 * @param {{ storageSuiteName?: string }} [options]
 */
function addEasAppExtension(config, bundleIdentifier, { storageSuiteName } = {}) {
  config.extra = config.extra ?? {};
  config.extra.eas = config.extra.eas ?? {};
  config.extra.eas.build = config.extra.eas.build ?? {};
  config.extra.eas.build.experimental = config.extra.eas.build.experimental ?? {};
  const ios = (config.extra.eas.build.experimental.ios = config.extra.eas.build.experimental.ios ?? {});
  ios.appExtensions = Array.isArray(ios.appExtensions) ? ios.appExtensions : [];
  const suite = typeof storageSuiteName === 'string' ? storageSuiteName.trim() : '';
  const entitlements = suite
    ? { 'com.apple.security.application-groups': [suite] }
    : {};
  const existing = ios.appExtensions.find(entry => entry?.targetName === NSE_TARGET_NAME);
  if (existing) {
    existing.entitlements = { ...(existing.entitlements ?? {}), ...entitlements };
  } else {
    ios.appExtensions.push({
      targetName: NSE_TARGET_NAME,
      bundleIdentifier: `${bundleIdentifier}.${NSE_BUNDLE_SUFFIX}`,
      entitlements,
    });
  }
  return config;
}

/**
 * Ensures `com.apple.security.application-groups` includes the suite (idempotent).
 * @param {Record<string, any>} entitlements
 * @param {string} storageSuiteName
 */
function ensureAppGroupEntitlement(entitlements, storageSuiteName) {
  const suite = typeof storageSuiteName === 'string' ? storageSuiteName.trim() : '';
  if (!suite) return entitlements;
  const key = 'com.apple.security.application-groups';
  const existing = entitlements[key];
  const groups = Array.isArray(existing) ? existing.slice() : [];
  if (!groups.includes(suite)) {
    groups.push(suite);
  }
  entitlements[key] = groups;
  return entitlements;
}

